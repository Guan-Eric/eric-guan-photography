const PRICE_PATTERN =
  /(\$|€|£|usd|cad|asking\s+price|listed\s+at|list\s+price|sale\s+price|sold\s+for|%?\s*over\s+(asking|list)|asking\b)/i;

export function suggestComplianceRegion(postalOrZip: string | null | undefined): ComplianceRegion {
  const raw = (postalOrZip ?? "").trim().toUpperCase().replace(/\s+/g, "");
  if (!raw) return "ca_other";
  if (/^[GHJ]/.test(raw)) return "ca_qc";
  // US ZIP (5 digits) or ZIP+4 — California starts with 90–96
  if (/^\d{5}(-\d{4})?$/.test(raw)) {
    const prefix = Number(raw.slice(0, 2));
    if (prefix >= 90 && prefix <= 96) return "us_ca";
  }
  return "ca_other";
}

