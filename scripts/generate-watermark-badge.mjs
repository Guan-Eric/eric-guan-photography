/**
 * Render the Studiofront corner badge (S icon + wordmark on a white pill)
 * stamped bottom-right on proof photos. Embedded as base64 because Workers
 * cannot read `public/` from disk at runtime.
 * Usage: node scripts/generate-watermark-badge.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const iconSrc = path.join(root, "public/studiofront-icon.png");
const lockupSrc = path.join(root, "public/studiofront-lockup.png");
const outFile = path.join(root, "lib/watermark-badge.ts");

const HEIGHT = 112;
const PAD_X = 30;
const GAP = 16;
const ICON_H = 64;
const LOCKUP_H = 42;

const icon = await sharp(iconSrc)
  .trim({ threshold: 10 })
  .resize({ height: ICON_H })
  .png()
  .toBuffer({ resolveWithObject: true });
const lockup = await sharp(lockupSrc)
  .trim({ threshold: 10 })
  .resize({ height: LOCKUP_H })
  .png()
  .toBuffer({ resolveWithObject: true });

const width = PAD_X * 2 + icon.info.width + GAP + lockup.info.width;
const pill = Buffer.from(
  `<svg width="${width}" height="${HEIGHT}" xmlns="http://www.w3.org/2000/svg">
    <rect width="${width}" height="${HEIGHT}" rx="${HEIGHT / 2}" fill="#ffffff" fill-opacity="0.9"/>
  </svg>`,
);

const png = await sharp(pill)
  .composite([
    {
      input: icon.data,
      left: PAD_X,
      top: Math.round((HEIGHT - icon.info.height) / 2),
    },
    {
      input: lockup.data,
      left: PAD_X + icon.info.width + GAP,
      top: Math.round((HEIGHT - lockup.info.height) / 2),
    },
  ])
  .png({ compressionLevel: 9 })
  .toBuffer();

fs.writeFileSync(
  outFile,
  `// Generated by scripts/generate-watermark-badge.mjs. Do not edit by hand.
export const WATERMARK_BADGE_WIDTH = ${width};
export const WATERMARK_BADGE_HEIGHT = ${HEIGHT};
export const WATERMARK_BADGE_PNG_BASE64 =
  "${png.toString("base64")}";
`,
);

console.log(`Wrote lib/watermark-badge.ts (${width}x${HEIGHT}, ${png.byteLength} bytes)`);
